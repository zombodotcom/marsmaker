"""Synthetic test site for the viewer's vehicle physics: parallel strips of constant side slope.

    python tools/make_ramp_site.py OUT_DIR [--bumps AMP_M]

Writes a one-tile MarsMaker site (meta.json + h_0_0.png, 1 m posts, 2017x2017). Strip i is
200 m wide (east-west), rises toward the east at ANGLES[i] degrees and runs the full 2 km
north-south, with 40 m nodata gaps between strips. Driving north (heading 0) along a strip's
centre holds a constant side slope. World coordinates (viewer): x = east = column, z = south = row.
Strip centre x is printed for use with --spawn X,1900 --heading 0.

--bumps adds smooth pseudo-random relief (default 0) to mimic dune texture.
"""
import json, sys, os
import numpy as np
from PIL import Image

ANGLES = [20, 25, 30, 35, 40, 45, 50]
N, STRIP, GAP = 2017, 200, 40


def main():
    out = sys.argv[1]
    bumps = float(sys.argv[sys.argv.index('--bumps') + 1]) if '--bumps' in sys.argv else 0.0
    os.makedirs(out, exist_ok=True)
    z = np.full((N, N), np.nan)
    r, c = np.mgrid[0:N, 0:N].astype(np.float64)
    rng = np.random.default_rng(1)
    relief = np.zeros((N, N))
    if bumps > 0:
        for _ in range(12):  # sum of a few smooth sinusoids, wavelengths 8-40 m
            k = rng.uniform(2 * np.pi / 40, 2 * np.pi / 8)
            a = rng.uniform(0, np.pi)
            relief += np.sin(k * (np.cos(a) * c + np.sin(a) * r) + rng.uniform(0, 6.3))
        relief *= bumps / np.abs(relief).max()
    centres = []
    for i, ang in enumerate(ANGLES):
        x0 = GAP // 2 + i * (STRIP + GAP)
        sl = slice(x0, x0 + STRIP + 1)
        z[:, sl] = np.tan(np.radians(ang)) * (c[:, sl] - x0) + relief[:, sl] + 10.0
        centres.append((ang, x0 + STRIP // 2))
    lo, hi = np.nanmin(z), np.nanmax(z)
    rng_m = hi - lo
    v = np.where(np.isnan(z), 0, 1 + np.round((z - lo) / rng_m * 65534)).astype(np.uint16)
    Image.fromarray(v).save(os.path.join(out, 'h_0_0.png'))
    meta = {
        'id': 'RAMPS', 'converter_version': 3,
        'description': "Synthetic test terrain. This product's rationale for creation was: side-slope ramps "
                       + '/'.join(map(str, ANGLES)) + " deg. This DTM was generated by make_ramp_site.py.",
        'metres_per_pixel': 1.0, 'tile_px': N, 'tile_overlap_px': 1, 'tile_size_m': N - 1,
        'grid_tiles': [1, 1], 'grid_px': [N, N], 'grid_top_left_m': {'east': 0.0, 'north': 0.0},
        'height_min_m': float(lo), 'height_max_m': float(hi), 'height_range_m': float(rng_m),
        'center_lat': 0.0, 'center_lon_east': 0.0,
        'tiles': [{'x': 0, 'y': 0, 'height': 'h_0_0.png', 'valid_fraction': float(np.isfinite(z).mean())}],
    }
    json.dump(meta, open(os.path.join(out, 'meta.json'), 'w'), indent=1)
    for ang, x in centres:
        print(f'{ang} deg strip: --spawn {x},1900 --heading 0')


if __name__ == '__main__':
    main()
